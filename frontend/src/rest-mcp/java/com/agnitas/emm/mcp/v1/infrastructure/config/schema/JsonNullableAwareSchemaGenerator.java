package com.agnitas.emm.mcp.v1.infrastructure.config.schema;

import java.lang.reflect.Method;
import java.lang.reflect.Parameter;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.RecordComponent;
import java.lang.reflect.Type;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;

import com.github.victools.jsonschema.generator.Module;
import com.github.victools.jsonschema.generator.OptionPreset;
import com.github.victools.jsonschema.generator.SchemaGenerator;
import com.github.victools.jsonschema.generator.SchemaGeneratorConfig;
import com.github.victools.jsonschema.generator.SchemaGeneratorConfigBuilder;
import com.github.victools.jsonschema.generator.SchemaVersion;
import com.github.victools.jsonschema.generator.Option;
import com.github.victools.jsonschema.module.jackson.JacksonOption;
import com.github.victools.jsonschema.module.jackson.JacksonSchemaModule;
import com.github.victools.jsonschema.module.swagger2.Swagger2Module;
import org.openapitools.jackson.nullable.JsonNullable;
import org.springframework.ai.mcp.annotation.method.tool.utils.McpJsonSchemaGenerator;
import org.springframework.ai.mcp.annotation.method.tool.utils.McpSpringAiSchemaModule;
import org.springframework.ai.util.JacksonUtils;
import org.springframework.ai.util.json.schema.JsonSchemaUtils;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.node.ObjectNode;

/**
 * Fixes schemas generated by Spring AI for tool parameters containing {@link JsonNullable} fields.
 * Regenerates only affected parameter schemas while preserving the original schema structure.
 * Remove once Spring AI provides native {@code JsonNullable} schema support
 * (<a href="https://github.com/spring-projects/spring-ai/issues/6046">issue #6046</a> /
 * <a href="https://github.com/spring-projects/spring-ai/pull/6071">PR #6071</a>).
 */
public final class JsonNullableAwareSchemaGenerator {

    private static final SchemaGenerator SUBTYPE_SCHEMA_GENERATOR;

    static {
        Module jacksonModule = new JacksonSchemaModule(JacksonOption.RESPECT_JSONPROPERTY_REQUIRED);
        Module openApiModule = new Swagger2Module();
        Module springAiSchemaModule = new McpSpringAiSchemaModule();
        Module jsonNullableModule = new JsonNullableSchemaModule();

        SchemaGeneratorConfigBuilder configBuilder = new SchemaGeneratorConfigBuilder(
                SchemaVersion.DRAFT_2020_12, OptionPreset.PLAIN_JSON)
                .with(jacksonModule)
                .with(openApiModule)
                .with(springAiSchemaModule)
                .with(jsonNullableModule)
                .with(Option.EXTRA_OPEN_API_FORMAT_VALUES)
                .with(Option.STANDARD_FORMATS)
                .with(Option.PLAIN_DEFINITION_KEYS)
                .without(Option.SCHEMA_VERSION_INDICATOR);

        SchemaGeneratorConfig config = configBuilder.build();
        SUBTYPE_SCHEMA_GENERATOR = new SchemaGenerator(config);
    }

    private JsonNullableAwareSchemaGenerator() {
    }

    /**
     * Returns {@code true} if any parameter of the given method is a record with at least one
     * {@link JsonNullable}-typed component, i.e. whether {@link #fixMethodSchema} has anything to do.
     */
    public static boolean needsFixup(Method method) {
        for (Parameter parameter : method.getParameters()) {
            if (hasJsonNullableComponent(parameter.getType())) {
                return true;
            }
        }
        return false;
    }

    public static String fixMethodSchema(Method method) {
        String baselineJson = McpJsonSchemaGenerator.generateForMethodInput(method);
        ObjectNode schema = (ObjectNode) JacksonUtils.getDefaultJsonMapper().readTree(baselineJson);
        JsonNode propertiesNode = schema.get("properties");
        if (!(propertiesNode instanceof ObjectNode properties)) {
            return baselineJson;
        }

        for (Parameter parameter : method.getParameters()) {
            if (!hasJsonNullableComponent(parameter.getType())) {
                continue;
            }

            String parameterName = parameter.getName();
            JsonNode existing = properties.get(parameterName);
            if (!(existing instanceof ObjectNode existingNode)) {
                continue;
            }
            String existingDescription = existingNode.has("description") ? existingNode.get("description").asString() : null;

            ObjectNode regenerated = SUBTYPE_SCHEMA_GENERATOR.generateSchema(parameter.getParameterizedType());
            JsonSchemaUtils.hoistDefsToRoot(schema, regenerated);
            if (existingDescription != null) {
                regenerated.put("description", existingDescription);
            }
            properties.set(parameterName, regenerated);
        }

        pruneUnreferencedDefs(schema);

        return schema.toPrettyString();
    }

    /**
     * Removes unused {@code $defs} left behind after replacing parameter schemas.
     */
    private static void pruneUnreferencedDefs(ObjectNode schema) {
        if (!(schema.get("$defs") instanceof ObjectNode defs)) {
            return;
        }

        Set<String> referencedKeys = new HashSet<>();
        collectDefReferences(schema, referencedKeys);

        for (String key : Set.copyOf(defs.propertyNames())) {
            if (!referencedKeys.contains(key)) {
                defs.remove(key);
            }
        }
        if (defs.isEmpty()) {
            schema.remove("$defs");
        }
    }

    private static void collectDefReferences(JsonNode node, Set<String> referencedKeys) {
        if (node.isObject()) {
            for (Map.Entry<String, JsonNode> entry : node.properties()) {
                if ("$ref".equals(entry.getKey()) && entry.getValue().isTextual()) {
                    String ref = entry.getValue().asString();
                    if (ref.startsWith("#/$defs/")) {
                        referencedKeys.add(ref.substring("#/$defs/".length()));
                    }
                } else {
                    collectDefReferences(entry.getValue(), referencedKeys);
                }
            }
        } else if (node.isArray()) {
            for (JsonNode element : node) {
                collectDefReferences(element, referencedKeys);
            }
        }
    }

    private static boolean hasJsonNullableComponent(Class<?> type) {
        if (!type.isRecord()) {
            return false;
        }
        for (RecordComponent component : type.getRecordComponents()) {
            Type genericType = component.getGenericType();
            if (genericType instanceof ParameterizedType parameterizedType
                    && parameterizedType.getRawType() == JsonNullable.class) {
                return true;
            }
        }
        return false;
    }

}
